def _safe_code(obj: Any, key: str = "code_icao") -> Optional[str]:
    """Safely extract a nested airport / operator code."""
    if isinstance(obj, dict):
        return obj.get(key) or obj.get("code_iata") or obj.get("code")
    return str(obj) if obj else None


def _parse_ts(value: Any) -> Optional[datetime]:
    """Parse an ISO-8601 timestamp string returned by AeroAPI."""
    if value is None:
        return None
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None


def transform_flights(raw_flights: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Normalise raw AeroAPI JSON into flat rows matching ``FLIGHT_SCHEMA``."""
    now = datetime.now(timezone.utc)
    rows: List[Dict[str, Any]] = []
    for flight in raw_flights:
        rows.append(
            {
                "fa_flight_id": flight.get("fa_flight_id", ""),
                "ident": flight.get("ident"),
                "operator": _safe_code(flight.get("operator")),
                "flight_number": flight.get("flight_number"),
                "aircraft_type": _safe_code(flight.get("aircraft_type"), "type"),
                "origin": _safe_code(flight.get("origin")),
                "destination": _safe_code(flight.get("destination")),
                "departure_time": _parse_ts(
                    flight.get("actual_off")
                    or flight.get("estimated_off")
                    or flight.get("scheduled_off")
                ),
                "arrival_time": _parse_ts(
                    flight.get("actual_on")
                    or flight.get("estimated_on")
                    or flight.get("scheduled_on")
                ),
                "status": flight.get("status"),
                "route_distance": (
                    float(flight["route_distance"])
                    if flight.get("route_distance") is not None
                    else None
                ),
                "ingest_timestamp": now,
            }
        )
    return rows


def to_dataframe(
    spark: SparkSession,
    rows: List[Dict[str, Any]],
    schema: StructType = FLIGHT_SCHEMA,
) -> DataFrame:
    """Create a PySpark DataFrame from a list of row dicts."""
    return spark.createDataFrame(rows, schema=schema)  # type: ignore[arg-type]


