class FlightAwareClient:
    """Thin wrapper around the FlightAware AeroAPI v4."""

    def __init__(self, api_key: str, base_url: str = AEROAPI_BASE_URL) -> None:
        self._base_url = base_url.rstrip("/")
        self._session = requests.Session()
        self._session.headers.update(
            {
                "x-apikey": api_key,
                "Accept": "application/json; charset=UTF-8",
            }
        )

    # ------------------------------------------------------------------
    # Public helpers
    # ------------------------------------------------------------------

    def fetch(
        self,
        endpoint: str,
        params: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute a GET request against the AeroAPI and return the JSON body.

        Raises
        ------
        requests.HTTPError
            If the API returns a non-2xx status code.
        """
        url = f"{self._base_url}{endpoint}"
        logger.info("GET %s  params=%s", url, params)
        response = self._session.get(url, params=params, timeout=30)
        response.raise_for_status()
        return response.json()

    def fetch_flights(
        self,
        endpoint: str = AEROAPI_ENDPOINT,
        params: Optional[Dict[str, Any]] = None,
    ) -> List[Dict[str, Any]]:
        """Fetch flight records, handling pagination transparently."""
        all_flights: List[Dict[str, Any]] = []
        next_cursor: Optional[str] = None

        while True:
            request_params = dict(params or {})
            if next_cursor:
                request_params["cursor"] = next_cursor

            data = self.fetch(endpoint, params=request_params)

            # AeroAPI wraps results under different keys depending on endpoint
            flights = (
                data.get("flights")
                or data.get("departures")
                or data.get("arrivals")
                or data.get("scheduled_departures")
                or data.get("scheduled_arrivals")
                or []
            )
            all_flights.extend(flights)

            # Pagination via the "links" object
            links = data.get("links")
            if links and links.get("next"):
                next_cursor = links["next"]
            else:
                break

        logger.info("Fetched %d flight records from %s", len(all_flights), endpoint)
        return all_flights


