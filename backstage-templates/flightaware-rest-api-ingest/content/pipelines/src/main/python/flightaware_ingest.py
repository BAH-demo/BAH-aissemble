def run_ingest(
    spark: SparkSession,
    api_key: str,
    endpoint: str = AEROAPI_ENDPOINT,
    params: Optional[Dict[str, Any]] = None,
) -> DataFrame:
    """Execute a single ingest cycle: fetch -> transform -> DataFrame.

    Parameters
    ----------
    spark:
        Active ``SparkSession``.
    api_key:
        FlightAware AeroAPI key.
    endpoint:
        API path to call (default comes from template configuration).
    params:
        Optional query-string parameters forwarded to the API.

    Returns
    -------
    DataFrame
        A PySpark DataFrame conforming to ``FLIGHT_SCHEMA``.
    """
    client = FlightAwareClient(api_key=api_key)
    raw = client.fetch_flights(endpoint=endpoint, params=params)
    if not raw:
        logger.warning("No flights returned from %s", endpoint)
        return spark.createDataFrame([], schema=FLIGHT_SCHEMA)
    rows = transform_flights(raw)
    return to_dataframe(spark, rows)


def run_polling_loop(
    spark: SparkSession,
    api_key: str,
    endpoint: str = AEROAPI_ENDPOINT,
    params: Optional[Dict[str, Any]] = None,
    interval: int = POLLING_INTERVAL_SECONDS,
) -> None:
    """Continuously poll the FlightAware API at the configured interval.

    Each cycle writes the result as a new micro-batch.  Override or extend
    this function to plug in your own persistence logic.
    """
    logger.info(
        "Starting FlightAware polling loop  endpoint=%s  interval=%ds",
        endpoint,
        interval,
    )
    while True:
        try:
            df = run_ingest(spark, api_key, endpoint, params)
            logger.info("Ingest cycle complete  rows=%d", df.count())
        except requests.HTTPError:
            logger.exception("AeroAPI request failed; retrying next cycle")
        except Exception:
            logger.exception("Unexpected error during ingest cycle")

        time.sleep(interval)
